/**
 * Process-wide wiring. Firebase initializes itself from google-services.json
 * through its content provider; when the build carries none, [firebaseReady]
 * is false, the account is unavailable and the sign-in screen says why.
 */
class TravelmoApplication : Application() {
    override fun onCreate() {
        super.onCreate()
        DebugLogging.install(this)
        // Off the main thread, so the first frame is normally at the chosen size.
        TextSizeSetting.warm(this)
        // The channel exists before any message arrives, so the first one is
        // shown rather than dropped for want of its channel.
        ReminderNotifications.ensureChannel(this)
    }

    val firebaseReady: Boolean by lazy { FirebaseApp.getApps(this).isNotEmpty() }

    val account: GoogleAccount by lazy {
        GoogleAccount(
            firebaseAvailable = { firebaseReady },
            // Generated by the google-services plugin from the Firebase project's
            // web client; absent (and so null) on a build without the JSON.
            webClientId = webClientId(),
        ).also { it.start() }
    }

    val trips: TripStore by lazy { FirestoreTrips() }

    /** Deleting the account through the parser; nothing without Firebase or a parser address. */
    val accountDeletion: AccountDeletion by lazy { if (firebaseReady) ParserAccountDeletion(BuildConfig.PARSER_URL) else NoAccountDeletion }

    /** Looking at an open trip's flights through the parser; nothing without Firebase or a parser address. */
    val flightRefresh: FlightRefresh by lazy { if (firebaseReady) ParserFlightRefresh(BuildConfig.PARSER_URL) else NoFlightRefresh }
    /** Linking email addresses through the parser; nothing without Firebase or a parser address. */
    val emailLinks: EmailLinks by lazy { if (firebaseReady) ParserEmailLinks(BuildConfig.PARSER_URL) else NoEmailLinks }

    /** Regrouping and deleting all trips through the parser; nothing without Firebase or a parser address. */
    val tripActions: TripActions by lazy { if (firebaseReady) ParserTripActions(ParserClient(BuildConfig.PARSER_URL)) else NoTripActions }

    /** Import review's "Import anyway" through the parser; nothing without Firebase or a parser address. */
    val importReview: ImportReview by lazy { if (firebaseReady) ParserImportReview(ParserClient(BuildConfig.PARSER_URL)) else NoImportReview }

    /** Settling the account's access with the parser; nothing without Firebase or a parser address. */
    val accessCheck: AccessCheck by lazy { if (firebaseReady) ParserAccessCheck(BuildConfig.PARSER_URL) else NoAccessCheck }

    /** This phone as a reminder device; nothing without Firebase. */
    val pushDevice: PushDevice by lazy { if (firebaseReady) FirebasePushDevice(this) else NoPushDevice }

    // By name rather than R.string: the resource exists only on a build where
    // the google-services plugin generated it, so a compile-time reference
    // would break the build without the JSON.
    @SuppressLint("DiscouragedApi")
    private fun webClientId(): String? {
        val id = resources.getIdentifier("default_web_client_id", "string", packageName)
        if (id == 0) TravelmoLog.warning("No default_web_client_id: google-services.json has no web OAuth client, so sign-in is off")
        return if (id == 0) null else getString(id)
    }
}
