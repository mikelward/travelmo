package app.travelmo

import android.annotation.SuppressLint
import android.app.Application
import app.travelmo.auth.GoogleAccount
import app.travelmo.data.FirestoreTrips
import app.travelmo.data.TripStore
import com.google.firebase.FirebaseApp

/**
 * Process-wide wiring. Firebase initializes itself from google-services.json
 * through its content provider; when the build carries none, [firebaseReady]
 * is false, the account is unavailable and the sign-in screen says why.
 */
class TravelmoApplication : Application() {
    val firebaseReady: Boolean by lazy { FirebaseApp.getApps(this).isNotEmpty() }

    val account: GoogleAccount by lazy {
        GoogleAccount(
            firebaseAvailable = { firebaseReady },
            // Generated by the google-services plugin from the Firebase project's
            // web client; absent (and so null) on a build without the JSON.
            webClientId = webClientId(),
        ).also { it.start() }
    }

    val trips: TripStore by lazy { FirestoreTrips() }

    // By name rather than R.string: the resource exists only on a build where
    // the google-services plugin generated it, so a compile-time reference
    // would break the build without the JSON.
    @SuppressLint("DiscouragedApi")
    private fun webClientId(): String? {
        val id = resources.getIdentifier("default_web_client_id", "string", packageName)
        return if (id == 0) null else getString(id)
    }
}
