// The airport tables (IATA code to time zone and to country and place) are
// the web's generated packages/core/src/airports.json and airportPlaces.json,
// the trip list's landmark drawings its landmarks.json, and the world map its apps/web/src/lib/worldMap.json, read from there
// rather than copied, so `pnpm --filter @travelmo/core airports` refreshes
// every app. They are compiled in as string constants, since iOS has no
// class-path resources.
abstract class GenerateCoreData : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val sources: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val dir = outputDir.get().asFile.resolve("app/travelmo/core")
        dir.deleteRecursively()
        dir.mkdirs()
        val out = StringBuilder("// Generated by :core:generateCoreData from the web's JSON tables. Do not edit.\n")
        out.append("package app.travelmo.core\n\n")
        for (file in sources.files.sortedBy { it.name }) {
            val name = file.nameWithoutExtension + "Json"
            // A JVM string constant holds at most 65,535 bytes, so long files
            // are joined from pieces well under that.
            val text = file.readText()
            val chunks = mutableListOf<String>()
            var at = 0
            while (at < text.length) {
                var end = minOf(at + 16_000, text.length)
                // Never between the halves of a surrogate pair.
                if (end < text.length && text[end - 1].isHighSurrogate()) end--
                chunks += text.substring(at, end)
                at = end
            }
            val pieces = chunks.joinToString(",\n") { piece ->
                val escaped = piece.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
                    .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
                "    \"$escaped\""
            }
            out.append("internal val $name: String get() = listOf(\n$pieces,\n).joinToString(\"\")\n\n")
        }
        dir.resolve("CoreData.kt").writeText(out.toString())
    }
}

val generateCoreData = tasks.register<GenerateCoreData>("generateCoreData") {
    sources.from(
        rootProject.file("../../packages/core/src/airports.json"),
        rootProject.file("../../packages/core/src/airportPlaces.json"),
        rootProject.file("../../packages/core/src/landmarks.json"),
        rootProject.file("../web/src/lib/worldMap.json"),
    )
    outputDir = layout.buildDirectory.dir("generated/coreData")
}

// Kotlin Multiplatform, so the iOS app shares this code with the Android
// app: the models and the logic shared with the web app's packages/core take
// strings and clocks and nothing else. The JVM target is what `:app` and
// `./gradlew :core:test` use, with no Android SDK; the iOS targets compile
// anywhere (klib cross-compilation) and run their tests only on a Mac.
// Nothing here can reach for a Context or a composable.
kotlin {
    jvmToolchain(21)
    jvm()
    iosArm64()
    iosSimulatorArm64()

    sourceSets {
        commonMain {
            kotlin.srcDir(generateCoreData)
            dependencies {
                api(libs.kotlinx.datetime)
            }
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(libs.kotest.assertions.core)
        }
        jvmTest.dependencies {
            implementation(project.dependencies.platform(libs.junit.bom))
            runtimeOnly(libs.junit.platform.launcher)
        }
        jvmMain.dependencies {
            // Self-test only: `-PverifyNoAndroidSelfTest` puts an Android artifact on
            // the classpath so CI can prove `verifyNoAndroid` fails.
            if (providers.gradleProperty("verifyNoAndroidSelfTest").isPresent) {
                implementation("androidx.core:core-ktx:1.13.1")
            }
        }
    }
}

